import {test, expect} from '@playwright/test'
test('private creation survives reload, denied outsiders and missing csrf', async ({page, browser}, testInfo) => {
  await page.goto('/')
  await page.getByLabel('Username').fill('owner')
  await page.getByLabel('Password').fill('synthetic-password')
  await page.getByRole('button', {name: 'Sign in', exact: true}).click()
  await expect(page.getByRole('heading', {name: 'Your repositories'})).toBeVisible()
  const name = 'browser-' + Date.now()
  await page.getByLabel('Repository name').fill(name)
  await page.getByRole('button', {name: 'Create private repository'}).click()
  await expect(page.getByRole('heading', {name: 'team / ' + name})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', {name: 'team / ' + name})).toBeVisible()
  const denied = await page.request.post('/api/repos', {data: {team: 'team', name: 'csrf-denied'}, headers: {'idempotency-key': 'csrf-denied'}})
  expect(denied.status()).toBe(403)
  const outsider = await browser.newContext({baseURL: process.env.GITGOOD_TEST_WEB_URL ?? 'http://localhost:47840', ignoreHTTPSErrors: process.env.GITGOOD_TEST_PRODUCTION === 'true'})
  const login = await outsider.request.post('/api/session', {data: {username: 'outsider', password: 'synthetic-password'}})
  expect(login.status()).toBe(200)
  const list = await outsider.request.get('/api/repos')
  expect((await list.json()).repositories).not.toEqual(expect.arrayContaining([expect.objectContaining({name})]))
  expect((await outsider.request.get('/api/repos/team/' + name)).status()).toBe(404)
  await outsider.close()
  await page.screenshot({path: testInfo.outputPath('repositories.png'), fullPage: true})
  await page.getByRole('link', {name: 'team / ' + name}).click()
  await expect(page.getByRole('heading', {name: 'Repository initialized'})).toBeVisible()
  await page.getByRole('link', {name: 'Your repositories'}).click()
  await page.getByRole('button', {name: 'Sign out'}).click()
  await expect(page.getByRole('heading', {name: 'Sign in to your installation'})).toBeVisible()
})
